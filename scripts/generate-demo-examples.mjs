import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { runDemo } from "../src/demo/orchestrator.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const generatedParent = join(root, ".augmentworks", "demo", "docs-examples");
const output = join(root, "docs/examples/demo-reports");
await rm(output, { recursive: true, force: true });
await rm(generatedParent, { recursive: true, force: true });
const result = await runDemo(
  {
    cwd: root,
    outputDirectory: generatedParent,
    json: true,
    handleSignals: false
  },
  { stderr: process.stderr }
);
if (!result.summary.ok || result.exitCode !== 0) {
  throw new Error("demo did not succeed; refusing to write documentation reports");
}
const faultyDir = result.records.find((record) => record.role === "faulty")?.artifacts.directory;
const passingDir = result.records.find((record) => record.role === "corrected")?.artifacts.directory;
if (faultyDir === undefined || passingDir === undefined) {
  throw new Error("demo records missing artifact directories");
}
await mkdir(join(output, "failing"), { recursive: true });
await mkdir(join(output, "passing"), { recursive: true });
for (const name of ["report.json", "junit.xml", "report.html"]) {
  await cp(join(faultyDir, name), join(output, "failing", name));
  await cp(join(passingDir, name), join(output, "passing", name));
}

const failing = JSON.parse(await readFile(join(output, "failing", "report.json"), "utf8"));
const excerpt = {
  _comment:
    "Normalized excerpt for documentation. Volatile run_id, timestamps, and attempt ids omitted. Raw reports in failing/ and passing/ retain provenance. Generated by npm run generate:demo-examples.",
  schema_version: failing.schema_version,
  outcome: failing.outcome,
  packet: failing.packet,
  observations: failing.attempts?.[0]?.observations ?? null,
  failed_assertions: (failing.attempts?.[0]?.assertions ?? []).filter((assertion) => assertion.passed === false)
};
await writeFile(join(output, "excerpt-normalized.json"), `${JSON.stringify(excerpt, null, 2)}\n`, "utf8");
process.stdout.write(`Wrote ${output}\n`);
