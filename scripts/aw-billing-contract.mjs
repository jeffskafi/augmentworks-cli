import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const LOCK_PATH = resolve(root, "contracts/aw-billing-v1.lock.json");
export const GENERATED_PATH = resolve(root, "src/billing/generated/contract.ts");
export const SCHEMA_PATH = resolve(root, "contracts/aw-billing-v1.schema.json");
export const FIXTURES_PATH = resolve(root, "contracts/aw-billing-v1.fixtures.json");

export function sha256Bytes(buffer) {
  return createHash("sha256").update(buffer).digest("hex");
}

export async function hashFile(path) {
  return sha256Bytes(await readFile(path));
}

export function generatedContractSource(lock) {
  return `/* Generated by scripts/aw-billing-contract.mjs. Do not edit by hand. */

export const AW_BILLING_CONTRACT = ${JSON.stringify(lock, null, 2)} as const;

export type AwBillingContract = typeof AW_BILLING_CONTRACT;
`;
}

export async function readLock() {
  return JSON.parse(await readFile(LOCK_PATH, "utf8"));
}

export async function writeGenerated(lock) {
  await writeFile(GENERATED_PATH, generatedContractSource(lock), "utf8");
}

export async function assertVendoredContract() {
  const lock = await readLock();
  const schemaHash = await hashFile(SCHEMA_PATH);
  const fixturesHash = await hashFile(FIXTURES_PATH);
  const errors = [];
  if (lock.schemaVersion !== "aw-billing/1") {
    errors.push(`lock schemaVersion is ${lock.schemaVersion}, expected aw-billing/1`);
  }
  if (lock.files["contracts/aw-billing-v1.schema.json"] !== schemaHash) {
    errors.push(
      `schema hash mismatch: lock ${lock.files["contracts/aw-billing-v1.schema.json"]} file ${schemaHash}`
    );
  }
  if (lock.files["contracts/aw-billing-v1.fixtures.json"] !== fixturesHash) {
    errors.push(
      `fixtures hash mismatch: lock ${lock.files["contracts/aw-billing-v1.fixtures.json"]} file ${fixturesHash}`
    );
  }
  const fixtures = JSON.parse(await readFile(FIXTURES_PATH, "utf8"));
  const advertised = lock.contract.advertisedCapabilities;
  if (JSON.stringify(advertised) !== JSON.stringify(fixtures.contract.advertisedCapabilities)) {
    errors.push("lock advertisedCapabilities diverge from vendored fixtures");
  }
  if (lock.contract.readScope !== fixtures.contract.readScope) {
    errors.push("lock readScope diverges from vendored fixtures");
  }
  const generated = generatedContractSource(lock);
  const committed = await readFile(GENERATED_PATH, "utf8");
  if (committed !== generated) {
    errors.push("src/billing/generated/contract.ts is out of date. Re-run the billing contract import.");
  }
  if (errors.length > 0) {
    throw new Error(errors.join("\n"));
  }
  return { lock, schemaHash, fixturesHash };
}
